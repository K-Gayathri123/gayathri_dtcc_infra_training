CREATE DATABASE IF NOT EXISTS EMPLOYEE_DB;

CREATE SCHEMA IF NOT EXISTS EMPLOYEE_DB.STAGING;

USE DATABASE EMPLOYEE_DB;
USE SCHEMA STAGING;


CREATE WAREHOUSE IF NOT EXISTS EMPLOYEE_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE EMPLOYEE_WH;


CREATE TABLE IF NOT EXISTS EMPLOYEE_DATA (
    EMPLOYEE_ID NUMBER,
    EMPLOYEE_NAME VARCHAR(100),
    DEPARTMENT VARCHAR(50),
    AGE VARCHAR(20),
    SALARY VARCHAR(30),
    CITY VARCHAR(50)
);


CREATE FILE FORMAT IF NOT EXISTS EMPLOYEE_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;



CREATE STAGE IF NOT EXISTS EMPLOYEE_STAGE
FILE_FORMAT = EMPLOYEE_CSV_FORMAT;

LIST @EMPLOYEE_STAGE;

COPY INTO EMPLOYEE_DATA
FROM @EMPLOYEE_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'EMPLOYEE_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';


SELECT COUNT(*)
FROM EMPLOYEE_DATA;

SELECT *
FROM EMPLOYEE_DATA;


SELECT
    EMPLOYEE_ID,
    COUNT(*) AS TOTAL_COUNT
FROM EMPLOYEE_DATA
GROUP BY EMPLOYEE_ID
HAVING COUNT(*) > 1;

SELECT *
FROM EMPLOYEE_DATA
WHERE EMPLOYEE_NAME IS NULL
   OR DEPARTMENT IS NULL
   OR AGE IS NULL
   OR SALARY IS NULL
   OR CITY IS NULL;

SELECT *
FROM EMPLOYEE_DATA
WHERE TRY_TO_NUMBER(SALARY) < 0;



SELECT
    MIN(TRY_TO_NUMBER(SALARY)) AS MIN_SALARY,
    MAX(TRY_TO_NUMBER(SALARY)) AS MAX_SALARY,
    AVG(TRY_TO_NUMBER(SALARY)) AS AVG_SALARY,
    SUM(TRY_TO_NUMBER(SALARY)) AS TOTAL_SALARY,
    MEDIAN(TRY_TO_NUMBER(SALARY)) AS MEDIAN_SALARY
FROM EMPLOYEE_DATA;



SELECT *
FROM EMPLOYEE_DATA
WHERE TRY_TO_NUMBER(AGE) <= 0;



SELECT
    DEPARTMENT,
    AVG(TRY_TO_NUMBER(SALARY)) AS AVG_SALARY
FROM EMPLOYEE_DATA
WHERE TRY_TO_NUMBER(SALARY) > 0
GROUP BY DEPARTMENT;